import fs from 'node:fs';
import path from 'node:path';

const packageDirectory = path.resolve(new URL('..', import.meta.url).pathname);
const migrationFile = path.join(packageDirectory, 'tokens.arizona-bootstrap-5-1.json');
const generatedCssFile = path.join(packageDirectory, 'dist', 'tokens.css');
const overrideFile = path.join(packageDirectory, 'arizona-bootstrap-5-1-overrides.css');
const migration = JSON.parse(fs.readFileSync(migrationFile, 'utf8'));
const generatedCss = fs.readFileSync(generatedCssFile, 'utf8');
const cssVariables = new Map(
  [...generatedCss.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)].map((match) => [match[1], match[2]])
);
const entries = [];
const currentTokens = new Set();

for (const group of Object.values(migration)) {
  for (const token of Object.values(group)) {
    const cssVariable = token.$extensions?.cssVariable;
    const currentToken = token.$extensions?.currentToken;
    if (!cssVariable || !currentToken) continue;

    const currentCssVariable = `--${currentToken.replaceAll('.', '-')}`;
    const targetCssVariable = cssVariable.endsWith('-rgb')
      ? `${currentCssVariable}-rgb`
      : currentCssVariable;
    const targetValue = cssVariables.get(targetCssVariable);
    if (!targetValue) {
      throw new Error(`Generated token ${targetCssVariable} was not found in ${generatedCssFile}`);
    }

    currentTokens.add(targetCssVariable);
    entries.push([cssVariable, targetCssVariable]);
  }
}

const output = [
  '/* Load this file after arizona-bootstrap.css. */',
  '/* Autogenerated from tokens.arizona-bootstrap-5-1.json and dist/tokens.css. DO NOT EDIT! */',
  ':root {',
  ...[...currentTokens].map((cssVariable) => `  ${cssVariable}: ${cssVariables.get(cssVariable)};`),
  ...entries.map(([cssVariable, targetCssVariable]) => `  ${cssVariable}: var(${targetCssVariable});`),
  '}',
  '',
].join('\n');

fs.writeFileSync(overrideFile, output);
console.log(`Wrote ${entries.length} overrides to ${path.relative(process.cwd(), overrideFile)}`);
