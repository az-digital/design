const cssVariableName = (id) => `--${id.replaceAll('.', '-')}`;

const toPercent = (value) => `${(Number(value) * 100).toFixed(2)}%`;

const colorDeclaration = (token) => {
  const { components } = token.$value;
  return `  ${cssVariableName(token.id)}: rgb(${toPercent(components[0])} ${toPercent(components[1])} ${toPercent(components[2])});`;
};

const rgbDeclaration = (token) => {
  const { components } = token.$value;
  const rgb = components.slice(0, 3).map((component) => Math.round(Number(component) * 255));
  return `  ${cssVariableName(token.id)}-rgb: ${rgb.join(', ')};`;
};

export default {
  name: '@az-digital/terrazzo-plugin-rgb',
  build({ tokens, outputFile }) {
    const declarations = Object.values(tokens)
      .filter((token) => token.$type === 'color' && token.$value && typeof token.$value === 'object' && 'components' in token.$value)
      .flatMap((token) => [colorDeclaration(token), rgbDeclaration(token)]);

    outputFile('tokens.css', `/* -------------------------------------------\n *  Autogenerated by @az-digital/terrazzo-plugin-rgb. DO NOT EDIT!\n * ------------------------------------------- */\n\n:root {\n${declarations.join('\n')}\n}\n`);
  },
};
